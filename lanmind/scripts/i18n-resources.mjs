import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const base = path.join(root, 'src/i18n/locales');
const locales = (await readdir(base, { withFileTypes: true })).filter((item) => item.isDirectory()).map((item) => item.name).sort();
const imports = [];
const resources = [];
const metadata = [];
for (const locale of locales) {
  const meta = JSON.parse(await readFile(path.join(base, locale, 'meta.json'), 'utf8'));
  metadata.push(meta);
  const entries = [];
  for (const file of (await readdir(path.join(base, locale))).filter((name) => name.endsWith('.json') && name !== 'meta.json').sort()) {
    const ns = file.slice(0, -5);
    const symbol = `r${imports.length}`;
    imports.push(`import ${symbol} from './locales/${locale}/${file}';`);
    entries.push(`${JSON.stringify(ns)}: ${symbol}`);
  }
  resources.push(`${JSON.stringify(locale)}: {${entries.join(', ')}}`);
}
const output = `// Generated by npm run i18n:generate. Edit locales instead.\n${imports.join('\n')}\nexport const resources = {${resources.join(',\n')}};\nexport const languageMetadata = ${JSON.stringify(metadata, null, 2)} as const;\nexport const localeCodes = ${JSON.stringify(locales)} as const;\n`;
const destination = path.join(root, 'src/i18n/resources.ts');
const previous = await readFile(destination, 'utf8').catch((error) => {
  if (error.code === 'ENOENT') return null;
  throw error;
});
if (previous !== output) await writeFile(destination, output);
